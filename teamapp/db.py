"""DB 접근. 운영은 Supabase(Postgres), 시험은 SQLite를 같은 SQL로 쓴다."""
import re
import sqlite3
import threading
from contextlib import contextmanager
from pathlib import Path

SCHEMA_PATH = Path(__file__).resolve().parent.parent / "schema.sql"


class Tx:
    """트랜잭션 하나. 결과는 dict 목록으로 돌려준다."""

    def __init__(self, cursor, fix_sql=lambda sql: sql):
        self.cursor = cursor
        self.fix_sql = fix_sql

    def run(self, sql, params=()):
        self.cursor.execute(self.fix_sql(sql), params)
        return self

    def rows(self, sql, params=()):
        self.run(sql, params)
        names = [d[0] for d in self.cursor.description]
        return [dict(zip(names, row)) for row in self.cursor.fetchall()]

    def one(self, sql, params=()):
        rows = self.rows(sql, params)
        return rows[0] if rows else None


class PostgresDb:
    """연결은 풀에서 재사용한다. prepare_threshold=None은 Supabase 풀러를 위한 설정이다."""

    def __init__(self, url):
        import psycopg
        from psycopg_pool import ConnectionPool
        self.integrity_error = psycopg.IntegrityError
        self.pool = ConnectionPool(
            url, min_size=1, max_size=4, open=True, timeout=20,
            kwargs={"prepare_threshold": None},
            check=ConnectionPool.check_connection,
        )

    @contextmanager
    def tx(self, lock=False):
        with self.pool.connection() as conn, conn.cursor() as cursor:
            if lock:
                # 쓰기를 한 번에 하나씩 처리해, 인원을 센 값이 처리 중에 바뀌지 않게 한다.
                cursor.execute("select pg_advisory_xact_lock(7320)")
            yield Tx(cursor)


def sqlite_schema(sql):
    sql = sql.replace("bigint generated by default as identity primary key",
                      "integer primary key autoincrement")
    sql = sql.replace("timestamptz not null default now()",
                      "text not null default current_timestamp")
    return re.sub(r"alter table \w+ enable row level security;", "", sql)


class SqliteDb:
    """Supabase 없이 규칙과 화면을 시험하기 위한 저장소."""

    integrity_error = sqlite3.IntegrityError

    def __init__(self, path=":memory:"):
        self.conn = sqlite3.connect(path, check_same_thread=False, isolation_level=None)
        self.conn.execute("pragma foreign_keys = on")
        self.conn.executescript(sqlite_schema(SCHEMA_PATH.read_text(encoding="utf-8")))
        self.lock = threading.RLock()

    @contextmanager
    def tx(self, lock=False):
        with self.lock:
            cursor = self.conn.cursor()
            cursor.execute("begin")
            try:
                yield Tx(cursor, lambda sql: sql.replace("%s", "?"))
            except BaseException:
                cursor.execute("rollback")
                raise
            cursor.execute("commit")


def connect(url):
    if url.startswith("sqlite:///"):
        return SqliteDb(url.removeprefix("sqlite:///"))
    return PostgresDb(url)
